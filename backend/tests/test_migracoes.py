import uuid
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

from app.config import get_settings

pytestmark = [pytest.mark.integration, pytest.mark.migration]
BACKEND = Path(__file__).resolve().parents[1]
TABELAS = {
    "usuarios",
    "perfis_evolucao",
    "documentos",
    "chunks",
    "adaptacoes",
    "eventos_xp",
    "conceitos_progresso",
    "testes_nivel",
}


@pytest.fixture
def url_descartavel(engine):
    base = make_url(get_settings().database_url)
    nome = f"adaptai_mig_{uuid.uuid4().hex[:8]}"
    admin = create_engine(base, isolation_level="AUTOCOMMIT")
    with admin.connect() as c:
        c.execute(text(f'CREATE DATABASE "{nome}"'))
    try:
        yield base.set(database=nome).render_as_string(hide_password=False)
    finally:
        with admin.connect() as c:
            c.execute(text(f'DROP DATABASE IF EXISTS "{nome}" WITH (FORCE)'))
        admin.dispose()


def _cfg(url: str) -> Config:
    cfg = Config(str(BACKEND / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND / "migrations"))
    cfg.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    return cfg


def _tabelas(url: str) -> set[str]:
    eng = create_engine(url)
    try:
        return set(inspect(eng).get_table_names()) - {"alembic_version"}
    finally:
        eng.dispose()


def test_upgrade_downgrade_upgrade(url_descartavel):
    cfg = _cfg(url_descartavel)
    command.upgrade(cfg, "head")
    assert _tabelas(url_descartavel) == TABELAS
    command.downgrade(cfg, "base")
    assert _tabelas(url_descartavel) == set()
    command.upgrade(cfg, "head")
    assert _tabelas(url_descartavel) == TABELAS


def test_um_unico_head():
    from alembic.script import ScriptDirectory

    cfg = Config(str(BACKEND / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND / "migrations"))
    assert len(ScriptDirectory.from_config(cfg).get_heads()) == 1


def test_modelo_e_migracao_nao_divergem(url_descartavel):
    cfg = _cfg(url_descartavel)
    command.upgrade(cfg, "head")
    command.check(cfg)  # levanta AutogenerateDiffsDetected se houver diferenca
